"""Layer 3: read submission text, surface document metadata, name outputs.

Output files are named by token. A real name must never reach a filename.

A docx carries names outside its visible text: the author, last-editor,
title, subject and comments properties, plus running headers and footers.
Every one of those strings must reach the caller as metadata, never
silently dropped and never silently folded into the body.

A docx table is body content too. Dropping it would silently grade an
incomplete essay, and a table-only submission would look identical to a
blank one, so an empty body is reported explicitly rather than inferred.
Tables are read in document order, alongside paragraphs, so a table that
sits between two paragraphs still reads in the order the student wrote it.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from zipfile import BadZipFile, ZipFile

TEXT_SUFFIXES = {".md", ".txt"}
MAX_FILE_BYTES = 25 * 1024 * 1024
MAX_DOCX_EXPANDED_BYTES = 100 * 1024 * 1024
MAX_DOCX_MEMBERS = 10_000
MAX_DOCX_COMPRESSION_RATIO = 100
MAX_EXTRACTED_CHARACTERS = 5_000_000
MAX_TABLE_DEPTH = 8


@dataclass(frozen=True)
class Extracted:
    """Text pulled from a submission, plus anything the container revealed.

    `metadata` holds identity-bearing strings the container carried outside
    the body -- document properties, headers, footers -- so the caller can
    tokenize them too. `empty_body` is True when the container read cleanly
    but the body itself is blank; that is a fact for the instructor to see,
    not an error.
    """

    text: str = ""
    metadata: tuple[str, ...] = ()
    empty_body: bool = False
    error: str = ""


_LIBRARY_DEFAULTS = {"generated by python-docx", "python-docx"}


def _docx_metadata(document) -> tuple[str, ...]:
    """Collect every identity-bearing string a docx carries outside the body.

    Two kinds of noise get filtered out here, not just blanks: python-docx's
    own default template values ("python-docx", "generated by python-docx"),
    which are not anyone's identity, and exact duplicates -- the same name
    often sits in both `author` and `last_modified_by`.
    """
    core = document.core_properties
    raw = [
        core.author,
        core.last_modified_by,
        core.title,
        core.subject,
        core.comments,
    ]
    for section in document.sections:
        raw.extend(paragraph.text for paragraph in section.header.paragraphs)
        raw.extend(paragraph.text for paragraph in section.footer.paragraphs)

    seen: set[str] = set()
    metadata = []
    for value in raw:
        if not value or value.strip().casefold() in _LIBRARY_DEFAULTS:
            continue
        if value in seen:
            continue
        seen.add(value)
        metadata.append(value)
    return tuple(metadata)


def _extract_docx(path: Path) -> Extracted:
    try:
        import docx  # type: ignore
        from docx.oxml.table import CT_Tbl
        from docx.oxml.text.paragraph import CT_P
        from docx.table import Table
        from docx.text.paragraph import Paragraph
    except ImportError:
        return Extracted(
            error="Reading .docx needs python-docx. Install it or convert to Markdown."
        )
    try:
        with ZipFile(path) as archive:
            members = archive.infolist()
            if len(members) > MAX_DOCX_MEMBERS:
                return Extracted(error=f"{path.name} has too many DOCX parts.")
            expanded = sum(member.file_size for member in members)
            if expanded > MAX_DOCX_EXPANDED_BYTES:
                return Extracted(error=f"{path.name} expands beyond the DOCX limit.")
            if any(
                member.file_size
                and member.file_size / max(member.compress_size, 1)
                > MAX_DOCX_COMPRESSION_RATIO
                for member in members
            ):
                return Extracted(error=f"{path.name} has an unsafe compression ratio.")
    except (BadZipFile, OSError) as exc:
        return Extracted(error=f"Could not read {path.name}: {exc}")
    try:
        document = docx.Document(str(path))
    except Exception as exc:  # noqa: BLE001 - report any container failure
        return Extracted(error=f"Could not read {path.name}: {exc}")

    def blocks(container):
        """Yield paragraphs and tables in the order they appear in a container."""
        for child in container.iterchildren():
            if isinstance(child, CT_P):
                yield Paragraph(child, document)
            elif isinstance(child, CT_Tbl):
                yield Table(child, document)

    def table_text(table, depth: int = 0) -> str:
        """Render a table as readable lines, skipping repeats from merged cells."""
        if depth > MAX_TABLE_DEPTH:
            raise ValueError(f"{path.name} nests tables too deeply.")
        lines = []
        for row in table.rows:
            seen_cells: set[int] = set()
            cells = []
            for cell in row.cells:
                key = id(cell._tc)
                if key in seen_cells:  # a merge repeats one cell per grid position
                    continue
                seen_cells.add(key)
                parts = []
                for block in blocks(cell._tc):
                    piece = (
                        block.text.strip()
                        if isinstance(block, Paragraph)
                        else table_text(block, depth + 1)
                    )
                    if piece:
                        parts.append(piece)
                cells.append(" ".join(parts))
            line = " | ".join(cells)
            if line.strip(" |"):
                lines.append(line)
        return "\n".join(lines)

    try:
        body_parts = []
        for block in blocks(document.element.body):
            piece = (
                block.text.strip()
                if isinstance(block, Paragraph)
                else table_text(block)
            )
            if piece:
                body_parts.append(piece)
        text = "\n\n".join(body_parts)
    except ValueError as exc:
        return Extracted(error=str(exc))
    if len(text) > MAX_EXTRACTED_CHARACTERS:
        return Extracted(error=f"{path.name} has too much extracted text.")

    metadata = _docx_metadata(document)
    return Extracted(text=text, metadata=metadata, empty_body=text.strip() == "")


def extract(path: Path) -> Extracted:
    """Return the text of a submission, or an error explaining why not."""
    suffix = path.suffix.lower()

    try:
        if path.is_symlink():
            return Extracted(error=f"{path.name} is a symbolic link, not a submission.")
        if path.stat().st_size > MAX_FILE_BYTES:
            return Extracted(
                error=f"{path.name} is too large. The limit is 25 MiB per file."
            )
    except OSError as exc:
        return Extracted(error=f"Could not read {path.name}: {exc}")

    if suffix in TEXT_SUFFIXES:
        try:
            text = path.read_text(encoding="utf-8-sig")
        except UnicodeDecodeError:
            return Extracted(
                error=f"{path.name} is not valid UTF-8. Re-save it as UTF-8 and try again."
            )
        except OSError as exc:
            return Extracted(error=f"Could not read {path.name}: {exc}")
        return Extracted(text=text, empty_body=text.strip() == "")

    if suffix == ".docx":
        return _extract_docx(path)

    if suffix == ".pdf":
        return Extracted(
            error=f"{path.name} is a PDF. Convert it to Markdown first; "
            "scanned submissions are out of scope."
        )

    return Extracted(error=f"{path.name} has an unsupported type: {suffix}")


def output_name(token: str, suffix: str = ".md") -> str:
    """Name a redacted file by its token so no real name reaches disk."""
    if "/" in suffix or "\\" in suffix or ".." in suffix:
        raise ValueError(f"Unsafe output suffix: {suffix!r}")
    return f"{token}{suffix}"
